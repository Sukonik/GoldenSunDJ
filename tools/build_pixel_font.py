U = 100                      # font units per pixel
CAP = 7
ASC = 8 * U
DESC = 2 * U
W = 6 * U                    # advance: 5px glyph + 1px gap

order = [".notdef"]
cmap = {}
glyphs = {}

def draw(rows):
    pen = TTGlyphPen(None)
    for r, line in enumerate(rows):
        for c, v in enumerate(line):
            if v == "1":
                x0, x1 = c * U, (c + 1) * U
                y1 = (CAP - r) * U + 0          # baseline at y=0
                y0 = y1 - U
                # clockwise square
                pen.moveTo((x0, y0)); pen.lineTo((x0, y1)); pen.lineTo((x1, y1)); pen.lineTo((x1, y0)); pen.closePath()
    return pen.glyph()

blank = "00000 " * 7
glyphs[".notdef"] = draw(["11111","10001","10001","10001","10001","10001","11111"])
for ch, rows in G.items():
    name = "uni%04X" % ord(ch)
    order.append(name); cmap[ord(ch)] = name; glyphs[name] = draw(rows)
# lowercase = same shapes (pixel small-caps style)
for ch in "abcdefghijklmnopqrstuvwxyz":
    cmap[ord(ch)] = "uni%04X" % ord(ch.upper())

fb = FontBuilder(1000, isTTF=True)
fb.setupGlyphOrder(order)
fb.setupCharacterMap(cmap)
fb.setupGlyf(glyphs)
fb.setupHorizontalMetrics({n: (W if n != ".notdef" else W, 0) for n in order})
fb.setupHorizontalHeader(ascent=ASC, descent=-DESC)
fb.setupNameTable({"familyName": "GSDJ Pixel", "styleName": "Regular",
                   "copyright": "GoldenSunDJ original pixel font",
                   "licenseDescription": "Created for GoldenSunDJ."})
fb.setupOS2(sTypoAscender=ASC, sTypoDescender=-DESC, usWinAscent=ASC, usWinDescent=DESC, sxHeight=7*U, sCapHeight=7*U)
fb.setupPost()
fb.font.flavor = "woff2"
fb.save("assets/fonts/gsdj-pixel.woff2")
print("glyphs:", len(order), "chars:", len(cmap))
